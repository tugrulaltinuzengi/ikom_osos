#!/usr/bin/env python3
"""Generate the compiled-in fallback profile for the gateway firmwares.

    python source/tools/gen_builtin.py          # rewrite
    python source/tools/gen_builtin.py --check  # fail if stale (CI)

Writes firmware-common/osos_builtin_dkm440.h (and the synced copy in the ESP8266
sketch folder, see sync_firmware_common.py). Registers go to flash (PROGMEM); the
display metadata is the profile JSON verbatim, so a gateway running only the
built-in still tells the app how to label its values.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import meterprofile as mp  # noqa: E402

SRC = os.path.join(HERE, "..", "meter-profiles", "dkm440.json")
OUT = os.path.join(HERE, "..", "firmware-common", "osos_builtin_dkm440.h")


def c_string(s, width=100):
    out = []
    for i in range(0, len(s), width):
        piece = s[i:i + width].replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    "{piece}"')
    return "\n".join(out)


def build():
    prof = mp.normalize(mp.load_profile(SRC))
    timing, regs = mp.resolve(prof)
    blob = mp.canonical_json(prof)
    assert blob.isascii()
    lines = [
        "// GENERATED by tools/gen_builtin.py from meter-profiles/dkm440.json - do not edit.",
        "// The profile the gateway falls back to when nothing is stored on flash:",
        "// the DATAKOM DKM-440, identical to the old compiled-in meter_map.h.",
        "#pragma once",
        '#include "osos_codec.h"',
        "",
        f"static const osos_reg_t kBuiltinRegs[{len(regs)}] PROGMEM = {{",
    ]
    for r in regs:
        order = (1 if r["word_order"] == "little" else 0) | (2 if r["byte_order"] == "little" else 0)
        lines.append(
            f'    {{ "{r["key"]}", {r["scale"]!r}, {r["offset"]!r}, {r["address"]}, {r["fc"]}, '
            f'{mp.TYPES[r["type"]][1]}, {order}, {r["decimals"]}, {{0, 0}} }},')
    lines += [
        "};",
        "",
        f"static const char kBuiltinBlob[] PROGMEM =",
        c_string(blob) + ";",
        "",
        "static const osos_builtin_t kBuiltin = {",
        f'    "{prof["id"]}",',
        f'    {{ {{\'O\', \'S\', \'P\', \'F\'}}, {mp.__dict__.get("PF_VER", 1)}, {len(regs)}, {prof["rev"]}, '
        f'{timing["read_gap_ms"]}, {timing["timeout_ms"]}, {timing["max_block"]}, '
        f'{timing["retries"]}, {len(blob)}, "{mp.wire_name(prof["name"])}" }},',
        "    kBuiltinRegs,",
        "    kBuiltinBlob,",
        "};",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("osos_builtin_dkm440.h is stale: run python source/tools/gen_builtin.py")
        print("builtin profile header is up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(OUT))

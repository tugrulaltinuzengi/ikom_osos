#!/usr/bin/env python3
"""Embed the shipped meter profiles in the web UI (browser-hmi/meter-map/shipped.js).

The page cannot fetch ../../meter-profiles when it is served from browser-hmi/ or
bundled in the Android app, so the three shipped profiles travel inside a script.

    python source/tools/gen_ui_profiles.py          # rewrite
    python source/tools/gen_ui_profiles.py --check  # fail if stale (CI)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import meterprofile as mp  # noqa: E402

PROFILES = os.path.join(HERE, "..", "meter-profiles")
OUT = os.path.join(HERE, "..", "browser-hmi", "meter-map", "shipped.js")
FILES = ["dkm440.json", "examples/sdm630.json", "examples/generic-int-scaled.json"]


def build():
    profiles = [mp.normalize(mp.load_profile(os.path.join(PROFILES, f))) for f in FILES]
    body = json.dumps(profiles, indent=1, ensure_ascii=False)
    return ("// GENERATED by tools/gen_ui_profiles.py from meter-profiles/ - do not edit.\n"
            "(function (root) {\n"
            "  root.OSOS_SHIPPED = " + body.replace("\n", "\n  ") + ";\n"
            "})(typeof self !== \"undefined\" ? self : this);\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("shipped.js is stale: run python source/tools/gen_ui_profiles.py")
        print("shipped.js is up to date")
    else:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(OUT))
